package com.examp.genifit.entity;

public enum ActivityLevel {
    SEDENTARY,          // Ít vận động (Ngồi văn phòng nhiều, hầu như không tập thể dục)
    LIGHTLY_ACTIVE,     // Vận động nhẹ (Đi bộ nhiều, tập thể dục nhẹ nhàng 1-3 ngày/tuần)
    MODERATELY_ACTIVE,  // Vận động vừa (Tập luyện thể thao khá nặng 3-5 ngày/tuần)
    VERY_ACTIVE         // Vận động nhiều (Lao động chân tay, hoặc tập rất nặng 6-7 ngày/tuần)
}
